//! The atm app (T-455, docs/guides/tauri.md): the dashboard in a window of its own, on atm-lib as `atm serve` is.
//!
//! Its commands are in `commands`; tauri-specta writes their TypeScript types (`.generated/app/bindings.ts`, never
//! edited by hand). The window may call only the commands its capability lists (`capabilities/main.json`).

pub mod commands;

use tauri::Manager;

use commands::{AppState, list_projects, version};

/// The app's commands, for Tauri and for the TypeScript types.
#[must_use]
pub fn commands() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(tauri_specta::collect_commands![version, list_projects])
}

/// Start the app: one instance (opening it again focuses the running window), the user's registry in its state.
///
/// # Panics
/// When Tauri can't start (no window system, a broken build).
pub fn run() {
    let commands = commands();
    tauri::Builder::default()
        // First, so a second instance stops before it sets anything up
        .plugin(tauri_plugin_single_instance::init(|app, _args, _cwd| {
            if let Some(window) = app.get_webview_window("main") {
                let _ = window.unminimize();
                let _ = window.show();
                let _ = window.set_focus();
            }
        }))
        .manage(AppState::new(atm_boot::open_registry()))
        .invoke_handler(commands.invoke_handler())
        .setup(move |app| {
            commands.mount_events(app);
            Ok(())
        })
        .run(context())
        .expect("the atm app");
}

/// The app's context (`tauri.conf.json`, the capabilities, the dashboard's files), made once: it can be generated only
/// once in a crate.
fn context<R: tauri::Runtime>() -> tauri::Context<R> {
    tauri::generate_context!()
}

#[cfg(test)]
mod tests {
    use super::commands::{AppError, projects};
    use super::*;
    use std::path::PathBuf;

    fn scratch(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("atm-app-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).expect("a scratch folder");
        dir
    }

    #[test]
    fn the_typescript_types_are_written_to_generated() {
        let path =
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../.generated/app/bindings.ts");
        std::fs::create_dir_all(path.parent().expect("a folder")).expect("the generated folder");
        commands()
            .export(
                specta_typescript::Typescript::default()
                    .header("// Generated by the atm app's tests (app/src-tauri/src/lib.rs): never edit by hand"),
                &path,
            )
            .expect("the bindings");
        let text = std::fs::read_to_string(&path).expect("the bindings file");
        assert!(
            text.contains("listProjects")
                && text.contains("ProjectEntry")
                && text.contains("AppError")
        );
    }

    #[test]
    fn an_empty_registry_lists_no_projects() {
        let home = scratch("empty");
        assert_eq!(projects(&atm_boot::open_registry_at(&home)), Ok(vec![]));
    }

    #[test]
    fn errors_keep_their_kind() {
        assert_eq!(
            AppError::from(atm_common::Error::failed("no")),
            AppError::Failed("no".into())
        );
        let json = serde_json::to_value(AppError::NotFound("T-1".into())).expect("json");
        assert_eq!(
            json,
            serde_json::json!({"kind": "not_found", "message": "T-1"})
        );
    }

    /// Through the app's own context, so its capability is what lets the window call them
    #[test]
    #[cfg_attr(
        windows,
        ignore = "T-482: Windows' local origin differs (http://tauri.localhost?)"
    )]
    fn the_main_windows_capability_lets_it_call_the_commands() {
        let home = scratch("ipc");
        let app = tauri::test::mock_builder()
            .manage(AppState::new(atm_boot::open_registry_at(&home)))
            .invoke_handler(tauri::generate_handler![version, list_projects])
            .build(context())
            .expect("the mock app");
        let window = tauri::WebviewWindowBuilder::new(&app, "main", tauri::WebviewUrl::default())
            .build()
            .expect("a window");
        let request = |command: &str, url: &str| tauri::webview::InvokeRequest {
            cmd: command.into(),
            callback: tauri::ipc::CallbackFn(0),
            error: tauri::ipc::CallbackFn(1),
            url: url.parse().expect("a URL"),
            body: tauri::ipc::InvokeBody::default(),
            headers: tauri::http::HeaderMap::default(),
            invoke_key: tauri::test::INVOKE_KEY.to_string(),
        };
        for (command, expected) in [
            ("version", serde_json::json!(atm_common::VERSION)),
            ("list_projects", serde_json::json!([])),
        ] {
            let answer =
                tauri::test::get_ipc_response(&window, request(command, "tauri://localhost"))
                    .expect(command);
            assert_eq!(
                answer.deserialize::<serde_json::Value>().expect("json"),
                expected
            );
            // A page from anywhere else, CompMD's sandbox frames included, gets nothing (docs/guides/tauri.md)
            let refused =
                tauri::test::get_ipc_response(&window, request(command, "https://example.com"));
            assert!(refused.is_err(), "{command} answered a remote page");
        }
    }
}
